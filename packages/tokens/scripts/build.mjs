// Builds every token output from src/tokens.json. No dependencies: `node scripts/build.mjs`.
//   dist/tokens.css        CSS variables with the legacy names (--surface, --radius-panel…) for non-Panda consumers
//   dist/panda-preset.js   a Panda CSS preset: tokens, semanticTokens (light/_dark), textStyles, keyframes
//   dist/theme-init.js     sets <html data-theme> from the OS before first paint and follows changes; <html data-font>
//   dist/dimensions.ts     every size as a plain number (px), components' own included, for any platform
//   dist/native.ts         plain values for React Native: hex/rgba colors per theme, numbers for sizes
//   dist/palette.ts        palettes at runtime, on any platform: createColors(palette, theme), checkPalette(palette)
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
// stripTypeScriptTypes is still marked experimental in Node 24; its warning is noise here.
const emitWarning = process.emitWarning;
process.emitWarning = (w, ...rest) => (/stripTypeScriptTypes/.test(String(w)) ? undefined : emitWarning.call(process, w, ...rest));
import { fileURLToPath } from 'node:url';
import { tokens, colorTokens, rawValue, resolveColor, isThemed, SCALE_RE, THEMES, REF_RE, SWAP_RE, palettes } from './load.mjs';
import { toNativeColor } from './color.mjs';
import { motion, keyframes } from './motion.mjs';

const DIST = fileURLToPath(new URL('../dist/', import.meta.url));
mkdirSync(DIST, { recursive: true });
const write = (f, s) => { writeFileSync(DIST + f, s); console.log(`  dist/${f}`); };
const banner = '// GENERATED by packages/tokens/scripts/build.mjs from src/tokens.json. Do not edit.\n';
const group = (key) => tokens[key].tokens;
const strip = (name, prefix) => name.replace(new RegExp(`^${prefix}-`), '');
// Built-in palettes other than the default, which is the primary-* / accent-* tokens themselves.
const extraPalettes = palettes.list.filter((p) => p.id !== palettes.default);
const SHADES = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];
const cap = (s) => s[0].toUpperCase() + s.slice(1);
// {x / 0.8} as CSS: the referenced color at 80%. color-mix with transparent keeps the hue and lightness exactly.
const mixAlpha = (ref, a) => `color-mix(in oklch, ${ref} ${+(a * 100).toFixed(2)}%, transparent)`;

// ---------- 1. tokens.css ----------
{
  const cssRef = (v) => { const m = v.match(REF_RE); return !m ? v : m[2] === undefined ? `var(--${m[1]})` : mixAlpha(`var(--${m[1]})`, +m[2]); };
  const light = [], dark = [];
  for (const t of colorTokens) {
    light.push(`  --${t.name}: ${cssRef(rawValue(t, 'light'))};`);
    if (isThemed(t)) dark.push(`  --${t.name}: ${cssRef(rawValue(t, 'dark'))};`);
  }
  for (const key of ['spacing', 'radius', 'size', 'shadow', 'blur', 'layer'])
    for (const t of group(key)) light.push(`  --${t.name}: ${t.value};`);
  light.push(`  --font-sans: ${tokens.type.families.sans};`);
  light.push(`  --ease-spring: ${motion.easings.spring};`, `  --duration-fast: ${motion.durations.fast};`);
  const typeRules = tokens.type.groups.flatMap((g) => g.styles.map((s) =>
    `.koi-type-${s.name} { font-family: var(--font-${g.family}); font-size: ${s.fontSize}; line-height: ${s.lineHeight}; font-weight: ${s.fontWeight}; }`));
  write('tokens.css', [
    '/* GENERATED from src/tokens.json. Light by default; dark with <html data-theme="dark">, or by the OS unless data-theme="light". */',
    ':root, [data-theme="light"] {', ...light, '}', '',
    '@media (prefers-color-scheme: dark) {', '  :root:not([data-theme="light"]) {', ...dark.map((l) => '  ' + l), '  }', '}', '',
    '[data-theme="dark"] {', ...dark, '}', '',
    // Palettes go on <html>, next to data-theme: the role variables are computed there.
    ...extraPalettes.flatMap((p) => [`[data-palette="${p.id}"] {`, ...['primary', 'accent'].flatMap((k) => Object.entries(p[k]).map(([step, v]) => `  --${k}-${step}: ${v};`)), '}', '']),
    '[data-font="chill"] {', `  --font-sans: ${tokens.type.families.chill};`, '}', '', ...typeRules, '',
  ].join('\n'));
}

// ---------- 2. panda-preset.js ----------
{
  // {primary-700} -> {colors.primary.700}; {action} -> {colors.action}
  const pandaName = (n) => { const m = n.match(SCALE_RE); return m ? `{colors.${m[1]}.${m[2]}}` : `{colors.${n}}`; };
  const pandaRef = (v) => { const m = v.match(REF_RE); return !m ? v : m[2] === undefined ? pandaName(m[1]) : mixAlpha(pandaName(m[1]), +m[2]); };
  const colors = {}, semantic = {};
  for (const t of colorTokens) {
    const m = t.name.match(SCALE_RE);
    // primary-* and accent-* are semantic so a palette can swap them: `_paletteRose` and so on, from <html data-palette>.
    // (globalCss can't do it: it lands in @layer base, which loses to the tokens layer.)
    if (m && SWAP_RE.test(t.name)) {
      const value = { base: t.value, ...Object.fromEntries(extraPalettes.map((p) => [`_palette${cap(p.id)}`, p[m[1]][m[2]]])) };
      (semantic[m[1]] ??= {})[m[2]] = { value, description: t.usage };
      continue;
    }
    if (m) { (colors[m[1]] ??= {})[m[2]] = { value: t.value, description: t.usage }; continue; }
    if (!isThemed(t)) { colors[t.name] = { value: t.value, description: t.usage }; continue; }
    const base = pandaRef(rawValue(t, 'light')), dk = pandaRef(rawValue(t, 'dark'));
    semantic[t.name] = { value: base === dk ? base : { base, _dark: dk }, description: t.usage };
  }
  const obj = (key, prefix) => Object.fromEntries(group(key).map((t) => [prefix ? strip(t.name, prefix) : t.name, { value: t.value, description: t.usage }]));
  const textStyles = {};
  for (const g of tokens.type.groups) for (const s of g.styles)
    textStyles[s.name] = { description: s.usage, value: { fontFamily: g.family, fontSize: s.fontSize, lineHeight: String(s.lineHeight), fontWeight: String(s.fontWeight) } };

  const preset = {
    name: '@koi/tokens',
    // Dark mode is driven by <html data-theme="dark">. dist/theme-init.js sets it from the OS
    // (and keeps following it) unless the app has chosen a theme. Check the generated CSS once:
    // semantic tokens should come out as `[data-theme=dark] { --colors-surface: … }`.
    // The font works the same way: <html data-font="chill"> swaps `sans` for ChillRoundF.
    conditions: { extend: { dark: '[data-theme=dark] &', light: '[data-theme=light] &', fontChill: '[data-font=chill] &',
      ...Object.fromEntries(extraPalettes.map((p) => [`palette${cap(p.id)}`, `[data-palette=${p.id}] &`])) } },
    theme: {
      extend: {
        tokens: {
          colors,
          spacing: obj('spacing', 'space'),
          radii: obj('radius', 'radius'),
          sizes: obj('size'),
          shadows: obj('shadow', 'shadow'),
          blurs: obj('blur', 'blur'),
          easings: Object.fromEntries(Object.entries(motion.easings).map(([k, v]) => [k, { value: v }])),
          durations: Object.fromEntries(Object.entries(motion.durations).map(([k, v]) => [k, { value: v }])),
          zIndex: Object.fromEntries(group('layer').map((t) => [strip(t.name, 'layer'), { value: t.value, description: t.usage }])),
        },
        semanticTokens: {
          colors: semantic,
          fonts: { sans: { value: { base: tokens.type.families.sans, _fontChill: tokens.type.families.chill } } },
        },
        textStyles,
        keyframes,
      },
    },
  };
  write('panda-preset.js', banner + `export const koiPreset = ${JSON.stringify(preset, null, 2)};\nexport default koiPreset;\n`);
  write('panda-preset.d.ts', banner + 'declare const koiPreset: any;\nexport { koiPreset };\nexport default koiPreset;\n');
}

// ---------- 3. theme-init.js ----------
write('theme-init.js', `/* GENERATED. Inline this in <head> before any CSS so there is no flash.
   Follows the OS unless localStorage "koi-theme" is "light" or "dark".
   Font: the system stack, or ChillRoundF when localStorage "koi-font" is "chill" (sets <html data-font="chill">).
   Palette: koiSetPalette("rose") picks a built-in one (<html data-palette>); koiSetPalette({ primary, accent }) with
   11-step scales sets a custom one as inline variables. Saved in localStorage "koi-palette"; koiSetPalette() resets. */
(function () {
  // The current choices live here; localStorage only carries them across reloads. When storage is blocked
  // (some private modes, sandboxed frames) the switches still work for the page.
  var mem = {};
  function load(k) { if (k in mem) return mem[k]; try { return localStorage.getItem(k); } catch (e) { return null; } }
  function save(k, v) { mem[k] = v; try { v == null ? localStorage.removeItem(k) : localStorage.setItem(k, v); } catch (e) {} }
  var el = document.documentElement, mq = window.matchMedia('(prefers-color-scheme: dark)');
  function apply() { var s = load('koi-theme'); el.setAttribute('data-theme', s === 'light' || s === 'dark' ? s : (mq.matches ? 'dark' : 'light')); }
  apply();
  mq.addEventListener('change', apply);
  window.koiSetTheme = function (t) { save('koi-theme', t || null); apply(); };
  function applyFont() { load('koi-font') === 'chill' ? el.setAttribute('data-font', 'chill') : el.removeAttribute('data-font'); }
  applyFont();
  window.koiSetFont = function (f) { save('koi-font', f === 'chill' ? f : null); applyFont(); };
  function applyPalette() { var p = null, st = el.style;
    try { p = JSON.parse(load('koi-palette')); } catch (e) {}
    for (var i = st.length - 1; i >= 0; i--) if (/^--(colors-)?(primary|accent)-\\d+$/.test(st[i])) st.removeProperty(st[i]);
    if (typeof p === 'string' && p !== ${JSON.stringify(palettes.default)}) { el.setAttribute('data-palette', p); return; }
    el.removeAttribute('data-palette');
    if (p && typeof p === 'object') ['primary', 'accent'].forEach(function (k) { for (var s in p[k]) {
      st.setProperty('--' + k + '-' + s, p[k][s]); st.setProperty('--colors-' + k + '-' + s, p[k][s]); } }); }
  applyPalette();
  window.koiSetPalette = function (p) { save('koi-palette', p ? JSON.stringify(p) : null); applyPalette(); };
})();
`);

// ---------- 4. dimensions.ts ----------
// Plain numbers. Recipes import `components` and wrap them with px(); native reads them as they are. The component
// group is not a Panda token category or a CSS variable on purpose: nothing themes it, and apps don't style with it.
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const px = (v) => { const n = parseFloat(v); if (!/px$/.test(v)) throw new Error(`Expected px: ${v}`); return n; };
const nums = (key, prefix) => Object.fromEntries(group(key).filter((t) => /px$/.test(t.value)).map((t) => [prefix ? strip(t.name, prefix) : t.name, px(t.value)]));
{
  // px, or unitless where the usage says so (the icon stroke is in 24-grid units).
  const value = (t) => { if (!/^-?[\d.]+(px)?$/.test(t.value)) throw new Error(`component.${t.name}: expected px or a number, got ${t.value}`); return parseFloat(t.value); };
  const components = Object.fromEntries(tokens.component.groups.map((g) => [camel(g.name), Object.fromEntries(g.tokens.map((t) => [camel(t.name), value(t)]))]));
  const layers = Object.fromEntries(group('layer').map((t) => [strip(t.name, 'layer'), t.value]));
  const body = { space: nums('spacing', 'space'), radii: nums('radius', 'radius'), sizes: nums('size'), layers, components };
  write('dimensions.ts', banner +
    '// Every size as a number in px (the icon stroke is in 24-grid units). Same on every platform: Panda recipes\n' +
    '// write `[${n}px]`, React Native and Tamagui use the numbers. `components` holds each component\'s own sizes;\n' +
    '// `layers` is the stacking order (z-index) of things that float over the page.\n' +
    Object.entries(body).map(([k, v]) => `export const ${k} = ${JSON.stringify(v, null, 2)} as const;`).join('\n\n') + '\n');
}

// ---------- 5. native.ts ----------
{
  const colors = Object.fromEntries(THEMES.map((th) => [th, Object.fromEntries(colorTokens.map((t) => [t.name, toNativeColor(resolveColor(t.name, th))]))]));
  const type = {};
  for (const g of tokens.type.groups) for (const s of g.styles) {
    const size = px(s.fontSize);
    const lh = typeof s.lineHeight === 'number' ? Math.round(size * s.lineHeight) : px(s.lineHeight);
    type[s.name] = { fontSize: size, lineHeight: lh, fontWeight: String(s.fontWeight) };
  }
  const body = {
    colors, blur: nums('blur', 'blur'), type,
    // CSS font stacks, for Expo web. On iOS / Android the system font is the default; ChillRoundF needs a full font file
    // loaded under that name (see the font decision in agent-doc/plan.md).
    fontStacks: tokens.type.families,
    motion: { springBezier: [0.47, 1.64, 0.41, 0.8], fastMs: 150 },
  };
  write('native.ts', banner +
    '// React Native has no CSS variables, no oklch() and no backdrop-filter: colors are pre-resolved per theme,\n' +
    '// sizes are plain numbers (dp). Shadows are not exported: build them per platform (iOS shadow*, Android elevation).\n' +
    "export { space, radii, sizes, layers, components } from './dimensions';\n\n" +
    Object.entries(body).map(([k, v]) => `export const ${k} = ${JSON.stringify(v, null, 2)} as const;`).join('\n\n') +
    '\n\nexport type ThemeName = keyof typeof colors;\nexport type ColorToken = keyof typeof colors.light;\n');
}
// ---------- 6. palette.ts ----------
// Palettes at runtime on any platform. The logic is src/palette-kit.ts; this binds it to the data. Then the build
// runs that same logic over the built-in palettes and checks it agrees with what it resolved itself (native.ts) and
// with `pnpm contrast`, so the runtime can't drift from the build.
{
  const hex = (v) => toNativeColor(v);
  const builtIn = Object.fromEntries(palettes.list.map((p) => [p.id, Object.fromEntries(['primary', 'accent'].map((k) =>
    [k, Object.fromEntries(SHADES.map((step) => [step, hex(resolveColor(`${k}-${step}`, 'light', p.id))]))]))]));
  const fixed = {}, roles = {};
  for (const t of colorTokens) {
    if (SWAP_RE.test(t.name)) continue;
    if (!isThemed(t)) { fixed[t.name] = hex(t.value); continue; }
    roles[t.name] = Object.fromEntries(THEMES.map((th) => {
      const v = rawValue(t, th), m = v.match(REF_RE);
      return [th, !m ? hex(v) : m[2] === undefined ? { ref: m[1] } : { ref: m[1], alpha: +m[2] }];
    }));
  }
  const pairs = JSON.parse(readFileSync(fileURLToPath(new URL('../src/contrast-pairs.json', import.meta.url)), 'utf8'));
  delete pairs.$comment;

  // Cross-check: load the kit (it has no imports, so stripping its types is enough) and run it on the same data.
  const kitSrc = stripTypeScriptTypes(readFileSync(fileURLToPath(new URL('../src/palette-kit.ts', import.meta.url)), 'utf8'));
  const { createPaletteKit } = await import('data:text/javascript,' + encodeURIComponent(kitSrc));
  const kit = createPaletteKit({ roles, fixed, pairs });
  for (const p of palettes.list) {
    const failures = kit.checkPalette(builtIn[p.id]);
    if (failures.length) throw new Error(`palette-kit: built-in palette "${p.id}" fails ${JSON.stringify(failures)}`);
    for (const th of THEMES) {
      const got = kit.createColors(builtIn[p.id], th);
      for (const name of Object.keys(roles)) {
        const want = hex(resolveColor(name, th, p.id));
        if (got[name] !== want) throw new Error(`palette-kit: ${p.id} ${th} ${name} is ${got[name]}, the build says ${want}`);
      }
    }
  }

  const json = (v) => JSON.stringify(v, null, 2);
  write('palette.ts', banner +
    `// Palettes at runtime: \`createColors(palettes.rose, 'dark')\` gives every role token's color; \`checkPalette(p)\`\n` +
    `// lists the contrast pairs a user-made palette fails. Colors are #rrggbb or rgba(), on every platform.\n` +
    `import { createPaletteKit, type Palette } from '../src/palette-kit';\n\n` +
    `export { SHADES } from '../src/palette-kit';\n` +
    `export type { ContrastFailure, Palette, Scale, Shade, Theme } from '../src/palette-kit';\n\n` +
    `export const palettes = ${json(builtIn)} as const satisfies Record<string, Palette>;\n\n` +
    `export type PaletteId = keyof typeof palettes;\n` +
    `export const defaultPalette: PaletteId = ${JSON.stringify(palettes.default)};\n\n` +
    `const roles = ${json(roles)} as const;\n\n` +
    `/** A role token: \`surface\`, \`action\`, \`text-muted\`… */\n` +
    `export type RoleToken = keyof typeof roles;\n\n` +
    `export const { createColors, checkPalette } = createPaletteKit<RoleToken>({\n` +
    `  roles,\n  fixed: ${json(fixed).replace(/\n/g, '\n  ')},\n  pairs: ${json(pairs).replace(/\n/g, '\n  ')},\n});\n`);
}

console.log('tokens built.');
